function render() {
  const t = copy[language];
  const path = (window.location.pathname.slice(BASE_PATH.length).replace(/\/+$/, "") || "/");
  const pages = {
    "/": homePage,
    "/a-propos": aboutPage,
    "/direction": leadershipPage,
    "/services": servicesPage,
    "/contact": contactPage
  };
  app.innerHTML = (pages[path] || notFoundPage)(t);
  document.documentElement.lang = language;
  document.title = `${path === "/" ? "Ets Garba" : t.nav[["/", "/a-propos", "/direction", "/services", "/contact"].indexOf(path)] || "Ets Garba"} — ${language === "fr" ? "Bangui, République centrafricaine" : "Bangui, Central African Republic"}`;
  document.querySelectorAll(".primary-nav a").forEach((link, index) => {
    link.textContent = t.nav[index];
    link.href = `${BASE_PATH}${link.dataset.route}`;
    link.classList.toggle("active", link.dataset.route === path);
    if (link.dataset.route === path) link.setAttribute("aria-current", "page");
    else link.removeAttribute("aria-current");
  });
  document.querySelector(".header-actions .button").innerHTML = `${t.quote} <span aria-hidden="true">↗</span>`;
  languageButton.textContent = language === "en" ? "FR" : "EN";
  languageButton.setAttribute("aria-label", language === "en" ? "Passer en français" : "Switch to English");
  document.querySelector(".skip-link").textContent = language === "en" ? "Skip to content" : "Aller au contenu";
  document.querySelector(".footer-motto").innerHTML = language === "en" ? "Rooted in Central Africa.<br><em>Connected to the world.</em>" : "Ancrés en Centrafrique.<br><em>Connectés au monde.</em>";
  document.querySelector(".footer-bottom a").textContent = t.nav[4];
  document.querySelectorAll("[data-route]").forEach(link => {
    link.href = `${BASE_PATH}${link.dataset.route}`;
  });
  document.querySelector(".skip-link").href = `${BASE_PATH}/#main`;
  document.querySelector("#year").textContent = new Date().getFullYear();
  document.querySelector(".sr-only").textContent = language === "en" ? "Open menu" : "Ouvrir le menu";
  menuButton.setAttribute("aria-expanded", "false");
  nav.classList.remove("is-open");
  const hash = window.location.hash;
  if (hash) requestAnimationFrame(() => document.getElementById(decodeURIComponent(hash.slice(1)))?.scrollIntoView());
  window.scrollTo({ top: 0, behavior: "instant" });
  wireForm(t);
}

function wireForm(t) {
  const form = document.querySelector("#quote-form");
  if (!form) return;
  const createMessage = () => {
    const data = new FormData(form);
    return [
      `${t.contactLabel} — Ets Garba`,
      `${t.formName}: ${data.get("name")}`,
      `${t.formOrg}: ${data.get("organisation") || "-"}`,
      `${t.formCountry}: ${data.get("country") || "-"}`,
      `${t.formService}: ${data.get("service") || "-"}`,
      "",
      `${t.formRequest}:`,
      data.get("request")
    ].join("\n");
  };
  form.addEventListener("submit", event => {
    event.preventDefault();
    if (!form.reportValidity()) return;
    const subject = encodeURIComponent(`${t.quote} — Ets Garba`);
    window.location.href = `mailto:contact@etsgarba.com?subject=${subject}&body=${encodeURIComponent(createMessage())}`;
  });
  document.querySelector("#copy-request").addEventListener("click", async () => {
    const status = document.querySelector("#form-status");
    if (!form.reportValidity()) return;
    try {
      await navigator.clipboard.writeText(createMessage());
      status.textContent = t.copied;
    } catch {
      status.textContent = t.copyError;
    }
  });
}

document.addEventListener("click", event => {
  const link = event.target.closest("a[data-route]");
  if (!link || event.metaKey || event.ctrlKey || event.shiftKey || event.altKey) return;
  event.preventDefault();
  history.pushState({}, "", `${BASE_PATH}${link.dataset.route}`);
  render();
});

